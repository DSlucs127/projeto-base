import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const functionsDir = path.resolve(scriptDir, '..');
const root = path.resolve(functionsDir, '..', '..');
const pluginsDir = path.join(root, 'plugins');
const output = path.join(functionsDir, 'src', 'generatedPlugins.ts');
const identifier = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function sourceImport(from, to) {
  const relative = path.relative(from, to).replaceAll('\\', '/').replace(/\.ts$/, '');
  return relative.startsWith('.') ? relative : `./${relative}`;
}

function activePlugins() {
  return fs.readdirSync(pluginsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith('_') && !entry.name.startsWith('.'))
    .sort((left, right) => left.name.localeCompare(right.name))
    .map((entry) => {
      const pluginDir = path.join(pluginsDir, entry.name);
      const manifestPath = path.join(pluginDir, 'plugin.json');
      if (!fs.existsSync(manifestPath)) {
        throw new Error(`Plugin "${entry.name}" is missing plugin.json`);
      }

      const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
      const modulePath = manifest?.functions?.module;
      const register = manifest?.functions?.register;
      if (typeof modulePath !== 'string' || !modulePath.startsWith('./functions/src/')) {
        throw new Error(`Plugin "${entry.name}" must declare a local functions/src TypeScript module`);
      }
      const sourcePath = path.resolve(pluginDir, modulePath);
      if (!sourcePath.startsWith(`${pluginDir}${path.sep}`) || !sourcePath.endsWith('.ts') || !fs.existsSync(sourcePath)) {
        throw new Error(`Plugin "${entry.name}" is missing the declared Functions module "${modulePath}"`);
      }
      if (typeof register !== 'string' || !identifier.test(register)) {
        throw new Error(`Plugin "${entry.name}" has an invalid functions.register export`);
      }
      return { importPath: sourceImport(path.dirname(output), sourcePath), register };
    });
}

const plugins = activePlugins();
const imports = plugins
  .map(({ importPath, register }, index) => `import { ${register} as registerPlugin${index} } from '${importPath}';`)
  .join('\n');
const registrars = plugins.map((_, index) => `  registerPlugin${index},`).join('\n');
const generated = `// Generated by scripts/bundle-plugins.mjs. Do not edit by hand.\n` +
  `import type { PluginRegistrar } from './pluginsRegistry';\n` +
  (imports ? `${imports}\n\n` : '\n') +
  `export const activePluginRegistrars: readonly PluginRegistrar[] = [\n` +
  (registrars ? `${registrars}\n` : '') +
  `];\n`;

if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== generated) {
  fs.writeFileSync(output, generated);
}

if (process.argv.includes('--clean')) {
  fs.rmSync(path.join(functionsDir, 'lib'), { recursive: true, force: true });
}

console.log(`[plugins] bundled ${plugins.length} active registrar(s) into the default Functions bundle`);
